CREATE TABLE document_templates (
    id_template BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL CHECK (length(btrim(name)) > 0),
    document_type VARCHAR(100) NOT NULL CHECK (length(btrim(document_type)) > 0),
    state VARCHAR(20) NOT NULL CHECK (state IN ('CURRENT', 'DRAFT', 'UNAVAILABLE')),
    deleted_at TIMESTAMP WITH TIME ZONE,
    revision BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE document_files (
    id_file BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_name VARCHAR(255) NOT NULL,
    relative_path VARCHAR(500) NOT NULL UNIQUE,
    mime_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    sha256 CHAR(64) NOT NULL,
    registered_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE template_versions (
    template_id BIGINT NOT NULL REFERENCES document_templates(id_template),
    version_number INTEGER NOT NULL CHECK (version_number > 0),
    file_id BIGINT NOT NULL UNIQUE REFERENCES document_files(id_file),
    static_document BOOLEAN NOT NULL,
    analysis_json JSONB NOT NULL,
    PRIMARY KEY (template_id, version_number)
);

CREATE TABLE template_version_fields (
    template_id BIGINT NOT NULL,
    version_number INTEGER NOT NULL,
    field_id BIGINT NOT NULL REFERENCES reference_fields(id_reference_field),
    required BOOLEAN NOT NULL,
    marker VARCHAR(54) NOT NULL CHECK (marker ~ '^\{\{[A-Z0-9_]{1,50}\}\}$'),
    PRIMARY KEY (template_id, version_number, field_id),
    FOREIGN KEY (template_id, version_number) REFERENCES template_versions(template_id, version_number)
);

CREATE TABLE document_registrations (
    confirmation_id UUID PRIMARY KEY,
    template_id BIGINT NOT NULL REFERENCES document_templates(id_template),
    request_hash CHAR(64) NOT NULL,
    file_hash CHAR(64) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    analysis_json JSONB NOT NULL,
    requirements_json JSONB NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    version_number INTEGER,
    failure VARCHAR(255),
    revision BIGINT NOT NULL DEFAULT 0,
    FOREIGN KEY (template_id, version_number) REFERENCES template_versions(template_id, version_number),
    CHECK ((status = 'COMPLETED') = (version_number IS NOT NULL))
);
CREATE INDEX document_registrations_template_idx ON document_registrations(template_id);

CREATE TABLE document_packages (
    id_package BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT REFERENCES cliente(id_cliente),
    name VARCHAR(150),
    state VARCHAR(20) NOT NULL CHECK (state IN ('DRAFT', 'CONFIRMED')),
    revision BIGINT NOT NULL DEFAULT 0,
    CHECK (state <> 'CONFIRMED' OR (client_id IS NOT NULL AND name IS NOT NULL AND length(btrim(name)) > 0)),
    UNIQUE (client_id, name)
);
CREATE TABLE document_package_templates (
    package_id BIGINT NOT NULL REFERENCES document_packages(id_package),
    template_id BIGINT NOT NULL REFERENCES document_templates(id_template),
    PRIMARY KEY (package_id, template_id)
);
