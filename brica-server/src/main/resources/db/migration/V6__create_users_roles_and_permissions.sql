CREATE TABLE permissions (
    id_permission BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    description TEXT
);

CREATE TABLE roles (
    id_role BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    hierarchy_level INTEGER NOT NULL,
    description TEXT,
    status INTEGER NOT NULL CHECK (status IN (0, 1))
);

CREATE TABLE role_permissions (
    role_id BIGINT NOT NULL REFERENCES roles(id_role),
    permission_id BIGINT NOT NULL REFERENCES permissions(id_permission),
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE app_users (
    id_user BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES roles(id_role),
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(8) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX idx_app_users_role ON app_users(role_id);

