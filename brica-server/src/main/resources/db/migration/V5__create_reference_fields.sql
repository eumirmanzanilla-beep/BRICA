CREATE TABLE reference_fields (
    id_reference_field BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key VARCHAR(50) NOT NULL,
    visible_name VARCHAR(50) NOT NULL,
    data_type VARCHAR(30) NOT NULL,
    origin VARCHAR(100) NOT NULL,
    source_path VARCHAR(150) NOT NULL,
    revision BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT uq_reference_fields_key UNIQUE (key),
    CONSTRAINT ck_reference_fields_key CHECK (key ~ '^[A-Z0-9_]{1,50}$'),
    CONSTRAINT ck_reference_fields_visible_name CHECK (visible_name ~ '[^[:space:]]'),
    CONSTRAINT ck_reference_fields_source CHECK (
        data_type = 'TEXT'
        AND source_path = 'name'
        AND origin IN ('WORK', 'CLIENT')
    )
);
