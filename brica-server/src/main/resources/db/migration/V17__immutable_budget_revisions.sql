CREATE TABLE budgets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, work_id BIGINT NOT NULL REFERENCES works(id_work),
 revision BIGINT NOT NULL DEFAULT 0, name VARCHAR(255) NOT NULL, principal_revision_id UUID,
 next_number INTEGER NOT NULL DEFAULT 1 CHECK(next_number>0), UNIQUE(id,work_id)
);
CREATE INDEX ix_budgets_work ON budgets(work_id,id);
CREATE TABLE budget_revisions (
 id UUID PRIMARY KEY, budget_id BIGINT NOT NULL REFERENCES budgets(id), revision_number INTEGER NOT NULL CHECK(revision_number>0),
 work_id BIGINT NOT NULL, job_id UUID NOT NULL, confirmation_id UUID NOT NULL,
 currency VARCHAR(3), subtotal NUMERIC, tax NUMERIC, total NUMERIC, justification VARCHAR(2000),
 control_policy VARCHAR(30) NOT NULL, notes JSONB NOT NULL, differences JSONB NOT NULL, confirmed_at TIMESTAMPTZ NOT NULL,
 UNIQUE(budget_id,revision_number), UNIQUE(budget_id,id),
 FOREIGN KEY(budget_id,work_id) REFERENCES budgets(id,work_id),
 FOREIGN KEY(job_id,work_id) REFERENCES extraction_jobs(id,work_id),
 FOREIGN KEY(confirmation_id,job_id) REFERENCES extraction_confirmations(id,job_id) DEFERRABLE INITIALLY DEFERRED
);
ALTER TABLE budgets ADD CONSTRAINT fk_budget_principal FOREIGN KEY(id,principal_revision_id) REFERENCES budget_revisions(budget_id,id);
CREATE TABLE budget_sections (
 id UUID PRIMARY KEY, revision_id UUID NOT NULL REFERENCES budget_revisions(id), position INTEGER NOT NULL CHECK(position>=0),
 title VARCHAR(1000) NOT NULL, UNIQUE(revision_id,id), UNIQUE(revision_id,position)
);
CREATE TABLE budget_items (
 id UUID PRIMARY KEY, revision_id UUID NOT NULL REFERENCES budget_revisions(id), section_id UUID,
 position INTEGER NOT NULL CHECK(position>=0), code VARCHAR(255), description TEXT NOT NULL CHECK(length(description) BETWEEN 1 AND 16384),
 unit VARCHAR(255), quantity NUMERIC, price NUMERIC, amount NUMERIC, evidence_id UUID, original_measurement VARCHAR(1000),
 UNIQUE(revision_id,position), FOREIGN KEY(revision_id,section_id) REFERENCES budget_sections(revision_id,id)
);
CREATE TRIGGER immutable_budget_revision BEFORE UPDATE OR DELETE ON budget_revisions FOR EACH ROW EXECUTE FUNCTION extraction_immutable_record();
CREATE TRIGGER immutable_budget_section BEFORE UPDATE OR DELETE ON budget_sections FOR EACH ROW EXECUTE FUNCTION extraction_immutable_record();
CREATE TRIGGER immutable_budget_item BEFORE UPDATE OR DELETE ON budget_items FOR EACH ROW EXECUTE FUNCTION extraction_immutable_record();
