ALTER TABLE works ADD CONSTRAINT uq_works_id_client UNIQUE (id_work, client_id);
ALTER TABLE document_templates
    ADD COLUMN client_id BIGINT REFERENCES cliente(id_cliente),
    ADD COLUMN work_id BIGINT,
    ADD CONSTRAINT fk_template_work_client FOREIGN KEY (work_id, client_id) REFERENCES works(id_work, client_id),
    ADD CONSTRAINT ck_template_scope CHECK (work_id IS NULL OR client_id IS NOT NULL);
CREATE INDEX document_templates_scope_idx ON document_templates(client_id, work_id, name, id_template);
ALTER TABLE document_packages
    ADD COLUMN work_id BIGINT,
    ADD CONSTRAINT fk_package_work_client FOREIGN KEY (work_id, client_id) REFERENCES works(id_work, client_id),
    ADD CONSTRAINT ck_package_scope CHECK (work_id IS NULL OR client_id IS NOT NULL);
-- Keep existing client-scoped names unique; allow the same name in different works.
ALTER TABLE document_packages DROP CONSTRAINT document_packages_client_id_name_key;
CREATE UNIQUE INDEX uq_package_client_name ON document_packages(client_id, name) WHERE work_id IS NULL;
CREATE UNIQUE INDEX uq_package_work_name ON document_packages(work_id, name) WHERE work_id IS NOT NULL;
CREATE INDEX document_packages_scope_idx ON document_packages(client_id, work_id, name, id_package);

CREATE TABLE work_attachments (
    id_attachment BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id BIGINT NOT NULL REFERENCES works(id_work),
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('CONTRACT', 'BASE_BUDGET')),
    original_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    relative_path VARCHAR(500) NOT NULL UNIQUE,
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    sha256 CHAR(64) NOT NULL,
    registered_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX work_attachments_work_idx ON work_attachments(work_id, id_attachment);
